def cache_formulas(path, cached):
    'Write calculated results beside formulas using standard-library ZIP/XML, allowing data_only reading without opening Excel. External formulas are never executed.'
    ns = 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'
    with zipfile.ZipFile(path) as archive:
        members = [(info, archive.read(info.filename)) for info in archive.infolist()]
    with zipfile.ZipFile(path,'w',compression=zipfile.ZIP_DEFLATED) as archive:
        for info,data in members:
            values = cached.get(info.filename)
            if values is not None:
                root = ET.fromstring(data)
                for cell in root.iter('{'+ns+'}c'):
                    address = cell.get('r')
                    if address not in values:
                        continue
                    if cell.find('{'+ns+'}f') is None:
                        raise ValueError(f'Cache without a formula: {info.filename}/{address}')
                    value = values[address]
                    v = cell.find('{'+ns+'}v')
                    if v is None:
                        v = ET.SubElement(cell,'{'+ns+'}v')
                    if value is None or isinstance(value,str):
                        cell.set('t','str')
                        v.text = '' if value is None else value
                    else:
                        cell.attrib.pop('t',None)
                        v.text = str(value)
                data = ET.tostring(root,encoding='utf-8',xml_declaration=True)
            archive.writestr(info,data)


