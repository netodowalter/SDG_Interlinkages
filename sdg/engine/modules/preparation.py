def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--input',type=Path,default=ROOT,help='API CSV or folder containing CSV files.')
    parser.add_argument('--output',type=Path,help='Output folder; default: same folder as the CSV.')
    parser.add_argument('--iges',type=Path,help='iges_correspondence.xlsx; default: CSV folder, script folder or embedded table.')
    parser.add_argument('--rules',type=Path,help='Optional JSON with specific mapping rules.')
    parser.add_argument('--start',type=int,default=2000)
    parser.add_argument('--end',type=int,default=2025)
    args = parser.parse_args(argv)
    if args.start>args.end:
        parser.error('--inicio deve ser menor ou igual a --fim.')
    if not args.input.exists():
        parser.error(f'Input not found: {args.input}')
    rules = {rule_key(r):r for r in DEFAULT_CONFIG['rules']}
    if args.rules:
        for r in json.loads(args.rules.read_text(encoding='utf-8-sig')):
            rules[rule_key(r)] = r
    files = [args.input] if args.input.is_file() else sorted(args.input.glob('*.csv'))
    files = [p for p in files if not p.name.startswith(('~$','.'))]
    processed = 0
    failures = 0
    outputs = set()
    for path in files:
        try:
            regions = read_csv_groups(path)
            if regions is None:
                if args.input.is_file():
                    raise ValueError('The CSV does not contain the expected API columns.')
                continue
            iges_path = args.iges
            if iges_path is None:
                iges_path = next((p for p in (path.parent/'iges_correspondence.xlsx',ROOT/'iges_correspondence.xlsx') if p.is_file()),None)
            iges = load_iges(iges_path)
            for code,region in regions.items():
                selections = select_series(iges,rules,region['groups'],args.start,args.end)
                n = sum(s['status']=='selected' for s in selections)
                output = (args.output or path.parent)/(f"{text(code).zfill(3)}_{filename_name(region['name'])}_SDG_API_{args.start}_{args.end}.xlsx")
                if output.resolve() in outputs:
                    raise ValueError(f'Two inputs would produce {output.name}; keep only one CSV version per region.')
                outputs.add(output.resolve())
                write_region(output,region['name'],code,selections,args.start,args.end,path.name)
                processed += 1
                print(f'Created: {output.name} — {n}/{len(selections)} targets with a numeric series.',flush=True)
                missing = [s['target'] for s in selections if s['status']!='selected']
                if missing:
                    print('  No numeric series (empty columns): '+', '.join(missing),flush=True)
        except Exception as exc:
            failures += 1
            print(f'ERROR in {path.name}: {exc}',file=sys.stderr,flush=True)
    if not processed:
        print('No CSV da API foi processado.',file=sys.stderr)
    return 1 if failures or not processed else 0


if __name__ == '__main__':
    sys.exit(main())
